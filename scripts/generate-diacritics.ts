// Regenerate the Diacritic property table used by unaccent().
import { createHash } from 'node:crypto';

const url = 'https://www.unicode.org/Public/17.0.0/ucd/PropList.txt';
const response = await fetch(url, { signal: AbortSignal.timeout(30_000) });
if (!response.ok) {
  throw new Error(`Unicode data download failed: ${response.status}`);
}
const data = await response.bytes();
if (createHash('sha256').update(data).digest('hex') !== '130dcddcaadaf071008bdfce1e7743e04fdfbc910886f017d9f9ac931d8c64dd') {
  throw new Error('Unicode 17.0 PropList checksum mismatch');
}
const ranges: [number, number][] = [];
for (const match of new TextDecoder().decode(data).matchAll(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*; Diacritic\s*#/gm)) {
  const start = Number.parseInt(match[1] ?? '', 16);
  const end = Number.parseInt(match[2] ?? match[1] ?? '', 16);
  const previous = ranges.at(-1);
  if (previous && previous[1] + 1 === start) {
    previous[1] = end;
  } else {
    ranges.push([start, end]);
  }
}
const lines = ranges.map(([lo, hi,]) => `    {0x${lo.toString(16)}, 0x${hi.toString(16)}},`);
await Bun.write(
  new URL('../native/diacritic_ranges.inc', import.meta.url),
  [
    '// Generated by scripts/generate-diacritics.ts from Unicode 17.0 PropList.txt.',
    '// Copyright 2025 Unicode, Inc. See THIRD_PARTY_NOTICES.md.',
    ...lines,
    '',
  ].join('\n'),
);
